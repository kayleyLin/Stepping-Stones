# 下面这两行是给 Python 版 (python3 run.py) 用的. 因为 Web端(JS API) 类型的 Key
# 是给浏览器 JS SDK 用的, 不能直接用在 Python 的 REST 请求里 —— 调 REST 接口
# 一定返回 INVALID_USER_KEY / USERKEY_PLAT_NOMATCH 之类的错误. 也就是说,
# 如果你的账号申请不到 Web服务 Key, Python 版目前没法接真实高德数据,
# 只能用 COMMUTE_PROVIDER = 'offline' 的本地估算. 如果你的账号恰好能申请到
# Web服务 Key (比如企业认证过), 才把它填在这里, 且要同时把 COMMUTE_PROVIDER 改成 'amap'.
AMAP_KEY = ''

# 数字签名私钥. 绝大多数情况留空即可.
#
# 只有一种情况需要填: 你在高德控制台给上面这个 Web服务 Key 主动开启了「数字签名」.
# 默认是关闭的, 关闭时填了反而会报错.
#
# 注意区分两种「安全密钥」, 它们长得一样但完全不通用:
#   1. JS API 的安全密钥 (securityJsCode) —— 配「Web端(JS API)」Key 用的,
#      填在网页版页面上, 跟这里的 AMAP_SECRET 无关.
#   2. Web服务 的数字签名私钥 —— 才是这一行要填的东西, 且前提是你能申请到 Web服务 Key.
#
# 拿不准就跑 python3 check_key.py, 它会告诉你手上是哪一种、能不能用.
